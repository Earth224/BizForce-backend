"use strict";
/* ══════════════════════════════════════════════════════════════════════════
   buildCardShell — writes lib/cardShell.generated.js from the frontend's
   card-view.html and the "/*" block of its _headers. The frontend is the
   source; GET /c/:slug and GET /card/:token (server.js, through
   lib/cardPage.js) serve this copy with a server-built head, and with the
   same security headers Netlify gives card-view.html.

     node scripts/buildCardShell.js          write lib/cardShell.generated.js
     node scripts/buildCardShell.js --check  write nothing; exit 1 if it differs

   The mirror of scripts/buildSupportPage.js, in the other direction: there
   the backend's template writes the frontend's support.html; here the
   frontend's card-view.html writes the backend's copy. Run it after changing
   card-view.html or _headers, then node scripts/buildAppMap.js.
   scripts/checkCardUpgrades.js fails until the two match.
   BIZFORCE_FRONTEND_DIR overrides the frontend location.
   ══════════════════════════════════════════════════════════════════════════ */

const fs = require("fs");
const path = require("path");

const FRONTEND = process.env.BIZFORCE_FRONTEND_DIR || path.join(__dirname, "..", "..", "BizForce-fronyend");
const OUT = path.join(__dirname, "..", "lib", "cardShell.generated.js");
const checkOnly = process.argv.indexOf("--check") !== -1;

/* The "/*" block of a Netlify _headers file: each indented "Name: value"
   line under it, in order. */
function headersOf(text) {
  const block = /^\/\*\n((?:[ \t]+[^\n]*\n?)+)/m.exec(String(text || "").replace(/\r\n/g, "\n"));
  const out = {};
  if (!block) return out;
  block[1].split("\n").forEach(function (l) {
    const m = /^\s+([A-Za-z-]+):\s*(.*)$/.exec(l);
    if (m) out[m[1]] = m[2].trim();
  });
  return out;
}

function generate(shell, headersText) {
  const headers = headersOf(headersText);
  return [
    "// GENERATED by scripts/buildCardShell.js from the frontend's card-view.html and _headers. Do not edit;",
    "// change the frontend and run node scripts/buildCardShell.js. lib/cardPage.js serves it.",
    "module.exports = {",
    "  SOURCE: \"card-view.html\",",
    "  HEADERS: " + JSON.stringify(headers, null, 2).replace(/\n/g, "\n  ") + ",",
    "  SHELL: " + JSON.stringify(shell),
    "};",
    ""
  ].join("\n");
}

module.exports = { headersOf, generate };

if (require.main === module) {
  if (!fs.existsSync(FRONTEND)) { console.error("Frontend not found: " + FRONTEND + " (set BIZFORCE_FRONTEND_DIR)."); process.exit(1); }
  const shell = fs.readFileSync(path.join(FRONTEND, "card-view.html"), "utf8").replace(/\r\n/g, "\n");
  const hdrs = fs.readFileSync(path.join(FRONTEND, "_headers"), "utf8");
  if (!Object.keys(headersOf(hdrs)).length) { console.error("_headers has no \"/*\" block of headers."); process.exit(1); }
  const text = generate(shell, hdrs);
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
  if (now === text) { console.log("unchanged  lib/cardShell.generated.js (" + Buffer.byteLength(text) + " bytes)"); process.exit(0); }
  if (checkOnly) { console.log("DIFFERS    lib/cardShell.generated.js — run node scripts/buildCardShell.js"); process.exit(1); }
  fs.writeFileSync(OUT, text);
  console.log("wrote      lib/cardShell.generated.js (" + Buffer.byteLength(text) + " bytes)");
}
