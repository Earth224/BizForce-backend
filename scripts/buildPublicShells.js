"use strict";
/* ══════════════════════════════════════════════════════════════════════════
   buildPublicShells (LR-4, Nov 25 2026) — writes lib/publicShells.generated.js
   from the frontend's seller.html and listing.html and the "/*" block of its
   _headers. The frontend is the source; GET /@:handle and GET /listing/:id
   (lib/getFoundRoutes.js, through lib/publicPages.js) serve these copies with a
   server-built head, so each page in the browser is exactly the frontend's.

     node scripts/buildPublicShells.js          write lib/publicShells.generated.js
     node scripts/buildPublicShells.js --check  write nothing; exit 1 if it differs

   The same rule as scripts/buildCardShell.js: run it after changing seller.html,
   listing.html or _headers, then node scripts/buildAppMap.js.
   scripts/checkGetFound.js fails until the copy matches.
   BIZFORCE_FRONTEND_DIR overrides the frontend location.
   ══════════════════════════════════════════════════════════════════════════ */

const fs = require("fs");
const path = require("path");
const { headersOf } = require("./buildCardShell");

const FRONTEND = process.env.BIZFORCE_FRONTEND_DIR || path.join(__dirname, "..", "..", "BizForce-fronyend");
const OUT = path.join(__dirname, "..", "lib", "publicShells.generated.js");

function unescapeHtml(s) { return String(s).replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&"); }

/* The page's own static description and title: what a page that is not shown keeps. */
function fallbackOf(shell, name) {
  const d = /\n  <meta name="description" content="([^"]*)"\/>/.exec(shell), t = /\n  <title>([^<]*)<\/title>/.exec(shell);
  if (!d || !t) throw new Error(name + ": no static description or title");
  return { description: unescapeHtml(d[1]), title: unescapeHtml(t[1]) };
}

function generate(seller, listing, headersText) {
  return [
    "// GENERATED by scripts/buildPublicShells.js from the frontend's seller.html, listing.html and _headers. Do not edit;",
    "// change the frontend and run node scripts/buildPublicShells.js. lib/publicPages.js serves them.",
    "module.exports = {",
    "  SOURCES: [\"seller.html\", \"listing.html\"],",
    "  HEADERS: " + JSON.stringify(headersOf(headersText), null, 2).replace(/\n/g, "\n  ") + ",",
    "  SELLER_FALLBACK: " + JSON.stringify(fallbackOf(seller, "seller.html")) + ",",
    "  LISTING_FALLBACK: " + JSON.stringify(fallbackOf(listing, "listing.html")) + ",",
    "  SELLER: " + JSON.stringify(seller) + ",",
    "  LISTING: " + JSON.stringify(listing),
    "};",
    ""
  ].join("\n");
}

function readSources(dir) {
  const lf = function (f) { return fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n"); };
  return { seller: lf("seller.html"), listing: lf("listing.html"), headers: lf("_headers") };
}

module.exports = { generate, readSources, fallbackOf, OUT };

if (require.main === module) {
  const checkOnly = process.argv.indexOf("--check") !== -1;
  if (!fs.existsSync(FRONTEND)) { console.error("Frontend not found: " + FRONTEND + " (set BIZFORCE_FRONTEND_DIR)."); process.exit(1); }
  const src = readSources(FRONTEND);
  if (!Object.keys(headersOf(src.headers)).length) { console.error("_headers has no \"/*\" block of headers."); process.exit(1); }
  const text = generate(src.seller, src.listing, src.headers);
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
  if (now === text) { console.log("unchanged  lib/publicShells.generated.js (" + Buffer.byteLength(text) + " bytes)"); process.exit(0); }
  if (checkOnly) { console.log("DIFFERS    lib/publicShells.generated.js — run node scripts/buildPublicShells.js"); process.exit(1); }
  fs.writeFileSync(OUT, text);
  console.log("wrote      lib/publicShells.generated.js (" + Buffer.byteLength(text) + " bytes)");
}
