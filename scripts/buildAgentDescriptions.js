"use strict";
/* ══════════════════════════════════════════════════════════════════════════
   buildAgentDescriptions — writes the frontend's agent descriptions from the
   one honest source, config/brain.js (PLATFORM_KNOWLEDGE.agents).

   It writes three things in the frontend checkout beside this repo:
     1. each agent page's <p class="agent-subtitle"> (the page is the one
        server.js's AGENT_PAGE_URLS names for that agent type);
     2. each agent card's <p> on index.html (the card under <h3>NAME</h3>);
     3. scripts/agent-descriptions.js, the map ai-agents.html reads.
   Nothing else in the frontend states an agent's description, and no page
   shows ai_agents.description (scripts/checkAgentDescriptions.js holds all of
   it to this).

   Run it after changing a description in config/brain.js, then rebuild the
   app map (node scripts/buildAppMap.js):
     node scripts/buildAgentDescriptions.js           writes what differs
     node scripts/buildAgentDescriptions.js --check   writes nothing; exit 1 if
                                                      anything would change
   BIZFORCE_FRONTEND_DIR overrides the frontend location.
   ══════════════════════════════════════════════════════════════════════════ */

const fs = require("fs");
const path = require("path");

const REPO = path.join(__dirname, "..");
const FRONTEND = process.env.BIZFORCE_FRONTEND_DIR || path.join(REPO, "..", "BizForce-fronyend");
const MAP_FILE = "scripts/agent-descriptions.js";

const lf = t => t.replace(/\r\n/g, "\n");
const escapeHtml = t => String(t).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/* type → page, read from server.js's AGENT_PAGE_URLS, the one list of agent pages. */
function agentPages(serverSource) {
  const start = serverSource.indexOf("const AGENT_PAGE_URLS = {");
  if (start < 0) throw new Error("AGENT_PAGE_URLS not found in server.js");
  const block = serverSource.slice(start, serverSource.indexOf("\n};", start));
  const out = {};
  const re = /^\s*([a-z_]+):\s*"([^"]+\.html)",?\s*$/gm;
  let m;
  while ((m = re.exec(block))) out[m[1]] = m[2];
  return out;
}

/* Each file as it should read, from the given sources (all strings). Pure: the
   check calls it on mutated text. Returns { files: { rel: text }, problems: [] }. */
function plan(opts) {
  const agents = opts.agents;                 // PLATFORM_KNOWLEDGE.agents
  const pages = agentPages(opts.server);
  const read = opts.read;                     // rel → current text (LF), or null
  const files = {};
  const problems = [];

  Object.keys(pages).forEach(function (type) {
    const agent = agents.find(a => a.key === type);
    if (!agent) { problems.push(type + ": a page but no description in config/brain.js"); return; }
    const rel = pages[type];
    const text = read(rel);
    if (text == null) { problems.push(rel + ": not found"); return; }
    const re = /<p class="agent-subtitle">[^<]*<\/p>/g;
    const found = text.match(re) || [];
    if (found.length !== 1) { problems.push(rel + ": " + found.length + " agent-subtitle paragraphs, expected 1"); return; }
    const want = '<p class="agent-subtitle">' + escapeHtml(agent.description) + "</p>";
    files[rel] = text.replace(re, () => want);
  });

  const index = read("index.html");
  if (index == null) problems.push("index.html: not found");
  else {
    let next = index;
    Object.keys(pages).forEach(function (type) {
      const agent = agents.find(a => a.key === type);
      if (!agent) return;
      const head = "<h3>" + escapeHtml(agent.name) + "</h3>";
      const at = next.split(head).length - 1;
      if (at !== 1) { problems.push("index.html: " + at + " cards headed " + head + ", expected 1"); return; }
      const i = next.indexOf(head) + head.length;
      const card = /^(\s*)<p>[^<]*<\/p>/.exec(next.slice(i));
      if (!card) { problems.push("index.html: no <p> under " + head); return; }
      next = next.slice(0, i) + card[1] + "<p>" + escapeHtml(agent.description) + "</p>" + next.slice(i + card[0].length);
    });
    files["index.html"] = next;
  }

  const map = {};
  agents.forEach(a => { map[a.key] = a.description; });
  files[MAP_FILE] =
    "/* GENERATED by BizForce-backend scripts/buildAgentDescriptions.js from\n" +
    "   config/brain.js (PLATFORM_KNOWLEDGE.agents). Do not edit: change the\n" +
    "   description there and run the script. Each agent's one honest description,\n" +
    "   by agent type; ai-agents.html shows these, never ai_agents.description. */\n" +
    "window.BF_AGENT_DESCRIPTIONS = Object.freeze(" + JSON.stringify(map, null, 2) + ");\n";

  return { files, problems, pages };
}

function readFrontend(rel) {
  const p = path.join(FRONTEND, rel);
  return fs.existsSync(p) ? lf(fs.readFileSync(p, "utf8")) : null;
}

function main() {
  const checkOnly = process.argv.indexOf("--check") !== -1;
  const brain = require(path.join(REPO, "config/brain.js"));
  const result = plan({ agents: brain.PLATFORM_KNOWLEDGE.agents, server: lf(fs.readFileSync(path.join(REPO, "server.js"), "utf8")), read: readFrontend });
  if (result.problems.length) {
    result.problems.forEach(p => console.error("PROBLEM  " + p));
    process.exit(1);
  }
  const changed = Object.keys(result.files).filter(rel => readFrontend(rel) !== result.files[rel]);
  if (checkOnly) {
    changed.forEach(rel => console.log("would change  " + rel));
    console.log(changed.length ? changed.length + " file(s) out of date" : "every agent description is current");
    process.exit(changed.length ? 1 : 0);
  }
  changed.forEach(function (rel) {
    const p = path.join(FRONTEND, rel);
    const before = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : "";
    const crlf = before.indexOf("\r\n") !== -1;
    fs.writeFileSync(p, crlf ? result.files[rel].replace(/\n/g, "\r\n") : result.files[rel]);
    console.log("wrote  " + rel);
  });
  console.log(changed.length ? changed.length + " file(s) written" : "nothing to write: every agent description is current");
}

module.exports = { plan, agentPages, escapeHtml, MAP_FILE };
if (require.main === module) main();
